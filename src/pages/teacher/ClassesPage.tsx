import { useEffect, useId, useState, type FormEvent } from 'react'
import { Link, useNavigate } from 'react-router'
import { ClassMark } from '../../components/Notebook'
import { Crumbs, ErrorNote, Field, Loading } from '../../components/ui'
import { usePageTitle } from '../../lib/pageTitle'
import { dayPhrase, formatJoinCode } from '../../lib/format'
import { errorMessage, supabase } from '../../lib/supabase'
import { loadOverview, prepFor, upcomingAssignments, type OvClass, type Overview } from '../../lib/teacherOverview'

/** All classes, each with its join code and how ready it is for the next assignment. */
export function ClassesPage() {
  usePageTitle('Classes')
  const navigate = useNavigate()
  const [data, setData] = useState<Overview | null>(null)
  const [courses, setCourses] = useState<{ id: string; title: string }[]>([])
  const [error, setError] = useState('')

  useEffect(() => {
    Promise.all([
      loadOverview({ notesLimit: 1 }),
      supabase
        .from('courses')
        .select('id, title')
        .order('created_at')
        .then(({ data, error }) => {
          if (error) throw error
          return data
        }),
    ])
      .then(([d, c]) => {
        setData(d)
        setCourses(c)
      })
      .catch((e) => setError(errorMessage(e)))
  }, [])

  if (!data) return <div className="page">{error ? <ErrorNote>{error}</ErrorNote> : <Loading label="Loading classes" />}</div>

  const active = data.classes.filter((c) => !c.archived)
  const archived = data.classes.filter((c) => c.archived)

  return (
    <div className="page teach">
      <Crumbs items={[{ label: 'Dashboard', to: '/teach' }, { label: 'Classes' }]} />
      <header className="pagehead">
        <h1>Classes</h1>
        <p className="muted">A class is a group of students with its own join code. Open one to see each student’s progress.</p>
      </header>
      <ErrorNote>{error}</ErrorNote>

      {courses.length === 0 ? (
        <p className="nothing">
          Classes take their lessons from a course. <Link to="/teach/courses">Make a course first</Link>.
        </p>
      ) : (
        <NewClass courses={courses} onCreated={(id) => navigate(`/teach/classes/${id}`)} onError={setError} />
      )}

      {active.length === 0 && courses.length > 0 && <p className="nothing">No classes yet.</p>}
      {active.length > 0 && (
        <ul className="rowlist">
          {active.map((c) => (
            <ClassRow key={c.id} c={c} data={data} />
          ))}
        </ul>
      )}

      {archived.length > 0 && (
        <details className="earlier">
          <summary>Archived classes ({archived.length})</summary>
          <ul className="rowlist">
            {archived.map((c) => (
              <ClassRow key={c.id} c={c} data={data} />
            ))}
          </ul>
        </details>
      )}
    </div>
  )
}

function ClassRow({ c, data }: { c: OvClass; data: Overview }) {
  const [next] = upcomingAssignments([{ ...c, archived: false }])
  const prep = next ? prepFor(next.a, c.students, data.progress) : null
  return (
    <li>
      <Link to={`/teach/classes/${c.id}`} className="rowlist__row">
        <span className="rowlist__main">
          <span className="rowlist__title">
            <ClassMark id={c.id} name={c.name} />
          </span>
          <span className="rowlist__sub">
            {c.courseTitle} · {c.students.length} {c.students.length === 1 ? 'student' : 'students'} · code{' '}
            <code>{formatJoinCode(c.joinCode)}</code>
          </span>
        </span>
        <span className="rowlist__side">
          {next && prep ? (
            <>
              Next: {next.a.title}, {dayPhrase(next.a.due_at)}
              <span className="rowlist__strong">
                {prep.ready.length}/{c.students.length} ready
              </span>
            </>
          ) : (
            <span className="muted">Nothing assigned ahead</span>
          )}
        </span>
        <span className="rowlist__go" aria-hidden="true">
          →
        </span>
      </Link>
    </li>
  )
}

function NewClass({
  courses,
  onCreated,
  onError,
}: {
  courses: { id: string; title: string }[]
  onCreated: (id: string) => void
  onError: (m: string) => void
}) {
  const [open, setOpen] = useState(false)
  const [name, setName] = useState('')
  const [courseId, setCourseId] = useState(courses[0]?.id ?? '')
  const selectId = useId()

  async function submit(e: FormEvent) {
    e.preventDefault()
    // join_code is generated by the database.
    const { data, error } = await supabase.from('classes').insert({ course_id: courseId, name: name.trim() }).select('id').single()
    if (error) return onError(errorMessage(error))
    onCreated(data.id)
  }

  if (!open)
    return (
      <p className="pagehead__actions">
        <button className="btn" onClick={() => setOpen(true)}>
          New class
        </button>
      </p>
    )
  return (
    <form className="inline-form newform" onSubmit={submit}>
      <Field label="Class name" placeholder="e.g. Period 2, Spring" required maxLength={200} value={name} onChange={(e) => setName(e.target.value)} />
      {courses.length > 1 && (
        <div className="field">
          <label htmlFor={selectId}>Lessons from course</label>
          <select id={selectId} value={courseId} onChange={(e) => setCourseId(e.target.value)}>
            {courses.map((c) => (
              <option key={c.id} value={c.id}>
                {c.title}
              </option>
            ))}
          </select>
        </div>
      )}
      <button className="btn">Create class</button>
      <button type="button" className="btn btn--ghost" onClick={() => setOpen(false)}>
        Cancel
      </button>
    </form>
  )
}
